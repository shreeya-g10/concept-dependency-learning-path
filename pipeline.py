"""Run the whole pipeline end to end.

    python pipeline.py --course ds101 [--target avl_tree]

Reads course files from data/raw/<course>/ and writes to outputs/<course>/.
Root-cause tracing runs only when outputs/<course>/student_answers.json exists.
Teacher decisions (outputs/<course>/review_decisions.json) are re-applied after validation.
Each step calls one module's CLI and checks its output against the contract.
Modules never import each other; they only exchange the files in outputs/<course>/.
"""

import argparse
import json
import subprocess
import sys
from pathlib import Path

from cdlp.shared.validate import check_file


def run(module: str, *args: str) -> None:
    print(f"\n==> {module}")
    subprocess.run([sys.executable, "-m", module, *args], check=True)


def default_target(graph_path: Path) -> str:
    """The concept with the most ancestors along ACCEPT edges (ties: alphabetical id).

    The deepest concept gives the longest, most informative learning path.
    """
    graph = json.loads(graph_path.read_text())
    parents: dict[str, set] = {}
    for edge in graph["edges"]:
        if edge["decision"] == "ACCEPT":
            parents.setdefault(edge["target"], set()).add(edge["source"])
    if not parents:
        raise SystemExit(f"no ACCEPT edges in {graph_path}; pass --target explicitly")

    def ancestors(node: str) -> set:
        seen, stack = set(), list(parents.get(node, ()))
        while stack:
            parent = stack.pop()
            if parent not in seen:
                seen.add(parent)
                stack.extend(parents.get(parent, ()))
        return seen

    counts = {node: len(ancestors(node)) for node in parents}
    target = min(counts, key=lambda node: (-counts[node], node))
    print(
        f"target: {target} ({counts[target]} ancestors via ACCEPT edges; pass --target to override)"
    )
    return target


def course_input(course: str) -> Path:
    """data/raw/<course>/, or data/raw/ while the course files still sit there."""
    folder = Path("data/raw") / course
    if folder.is_dir():
        return folder
    print(f"note: {folder} not found, reading data/raw/ instead")
    return Path("data/raw")


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--course", default="ds101")
    parser.add_argument("--input", help="default: data/raw/<course>/")
    parser.add_argument(
        "--target", help="default: the concept with the most ancestors among ACCEPT edges"
    )
    parser.add_argument("--out-dir", help="default: outputs/<course>/")
    parser.add_argument(
        "--allow-tfidf",
        action="store_true",
        help="passed to extraction: deduplicate with TF-IDF if the embedding model fails",
    )
    parser.add_argument(
        "--skip-necessity",
        action="store_true",
        help="passed to validation: skip the report-only necessity test (quick builds)",
    )
    parser.add_argument(
        "--demo-subset",
        type=int,
        help="passed to validation: validate only the N highest-confidence edges (a demo)",
    )
    parser.add_argument(
        "--allow-rule-based",
        action="store_true",
        help="passed to extraction: keyword-catalog concepts if the LLM is unreachable",
    )
    args = parser.parse_args()
    raw = Path(args.input) if args.input else course_input(args.course)
    out = Path(args.out_dir) if args.out_dir else Path("outputs") / args.course
    out.mkdir(parents=True, exist_ok=True)

    extraction_args = ["--input", str(raw), "--out-dir", str(out), "--course-id", args.course]
    extraction_args += ["--allow-tfidf"] if args.allow_tfidf else []
    extraction_args += ["--allow-rule-based"] if args.allow_rule_based else []
    run("cdlp.extraction", *extraction_args)
    run(
        "cdlp.discovery",
        "--concepts",
        str(out / "concepts.json"),
        "--chunks",
        str(out / "chunks.jsonl"),
        "--out-dir",
        str(out),
    )
    run(
        "cdlp.validation",
        "--relationships",
        str(out / "relationships.json"),
        "--concepts",
        str(out / "concepts.json"),
        "--chunks",
        str(out / "chunks.jsonl"),
        "--out",
        str(out / "validated_graph.json"),
        *(["--skip-necessity"] if args.skip_necessity else []),
        *(["--demo-subset", str(args.demo_subset)] if args.demo_subset else []),
    )
    # teacher decisions (website review page) survive a re-run: apply them to the new graph
    if (out / "review_decisions.json").exists():
        run(
            "cdlp.validation.apply_review",
            "--graph",
            str(out / "validated_graph.json"),
            "--decisions",
            str(out / "review_decisions.json"),
        )
    # Quiz items for this course, generated by the LLM from its own chunks (any course ID).
    # Only concepts on ACCEPT edges: paths and the diagnosis never reach the others.
    quiz_items = out / "quiz_items.json"
    run(
        "cdlp.learning_path.quiz",
        "--concepts",
        str(out / "concepts.json"),
        "--chunks",
        str(out / "chunks.jsonl"),
        "--course-id",
        args.course,
        "--out",
        str(quiz_items),
        "--only-graph",
        str(out / "validated_graph.json"),
    )
    # learning_path (cdlp/learning_path/sim_students.py) generates sim_students.json from
    # the validated graph itself.
    run(
        "cdlp.learning_path",
        "--graph",
        str(out / "validated_graph.json"),
        "--quiz",
        str(quiz_items),
        "--target",
        args.target or default_target(out / "validated_graph.json"),
        "--out-dir",
        str(out),
    )
    if (out / "student_answers.json").exists():
        root_cause_args = [
            "--graph",
            str(out / "validated_graph.json"),
            "--quiz",
            str(quiz_items),
            "--answers",
            str(out / "student_answers.json"),
            "--out",
            str(out / "root_cause.json"),
        ]
        # the tracer uses each student's mastery when learning_path has written it
        if (out / "student_state.json").exists():
            root_cause_args += ["--state", str(out / "student_state.json")]
        run("cdlp.root_cause", *root_cause_args)
    else:
        print("\n==> cdlp.root_cause skipped (no student_answers.json)")

    print("\n==> contract check")
    failed = False
    for path in sorted(out.iterdir()):
        errors = check_file(path)
        print(f"[{'OK' if not errors else 'FAIL'}] {path}")
        failed |= bool(errors)
    sys.exit(1 if failed else 0)


if __name__ == "__main__":
    main()
