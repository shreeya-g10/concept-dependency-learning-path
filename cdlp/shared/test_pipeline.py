"""pipeline.py smoke test for ds101 and ml101, with no LLM.

The three LLM stages (extraction, discovery, validation) are replaced by fakes that
write the shared examples, relabelled with the course_id they received: extraction
from --course-id, later stages from their input file. learning_path, which makes no
LLM call, runs for real. The test checks the step order, the arguments each module
gets, and that course_id is right in every file in the output folder.
"""

import importlib.util
import json
from pathlib import Path

import pytest

from cdlp.shared.io import EXAMPLES

ROOT = Path(__file__).resolve().parents[2]


def load_pipeline():
    spec = importlib.util.spec_from_file_location("pipeline", ROOT / "pipeline.py")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def arg(args, flag):
    return args[args.index(flag) + 1]


def relabel(src: Path, dst: Path, course: str) -> None:
    if src.suffix == ".jsonl":
        rows = [json.loads(line) for line in src.read_text().splitlines() if line.strip()]
        dst.write_text("".join(json.dumps({**r, "course_id": course}) + "\n" for r in rows))
    else:
        dst.write_text(json.dumps({**json.loads(src.read_text()), "course_id": course}))


def course_of(path: Path) -> str:
    return json.loads(Path(path).read_text())["course_id"]


@pytest.mark.parametrize("course", ["ds101", "ml101"])
def test_pipeline_runs_and_keeps_course_id(course, tmp_path, monkeypatch, capsys):
    pipeline = load_pipeline()
    real_run = pipeline.run
    calls = []

    def fake_run(module, *args):
        calls.append((module, args))
        if module == "cdlp.extraction":
            out = Path(arg(args, "--out-dir"))
            cid = arg(args, "--course-id")
            relabel(EXAMPLES / "concepts.json", out / "concepts.json", cid)
            relabel(EXAMPLES / "chunks.jsonl", out / "chunks.jsonl", cid)
        elif module == "cdlp.discovery":
            out = Path(arg(args, "--out-dir"))
            cid = course_of(arg(args, "--concepts"))
            relabel(EXAMPLES / "relationships.json", out / "relationships.json", cid)
        elif module == "cdlp.validation":
            cid = course_of(arg(args, "--relationships"))
            relabel(EXAMPLES / "validated_graph.json", Path(arg(args, "--out")), cid)
        else:  # learning_path and root_cause make no LLM call: run them for real
            real_run(module, *args)

    monkeypatch.setattr(pipeline, "run", fake_run)
    monkeypatch.setattr("sys.argv", ["pipeline.py", "--course", course, "--out-dir", str(tmp_path)])

    with pytest.raises(SystemExit) as exit_info:
        pipeline.main()

    assert exit_info.value.code == 0, capsys.readouterr().out  # contract check passed
    modules = [m for m, _ in calls]
    assert modules == ["cdlp.extraction", "cdlp.discovery", "cdlp.validation", "cdlp.learning_path"]

    args = dict(calls)
    assert arg(args["cdlp.extraction"], "--course-id") == course
    assert "--students" not in args["cdlp.learning_path"]  # learning_path builds them
    # no --target given: the example graph's deepest ACCEPT concept is chosen and printed
    assert arg(args["cdlp.learning_path"], "--target") == "avl_tree"
    assert "target: avl_tree (4 ancestors" in capsys.readouterr().out

    produced = sorted(p.name for p in tmp_path.iterdir())
    assert "sim_students.json" in produced  # generated by learning_path from the graph
    for path in tmp_path.iterdir():
        if path.suffix == ".jsonl":
            rows = [json.loads(line) for line in path.read_text().splitlines() if line.strip()]
            assert {r["course_id"] for r in rows} == {course}, path.name
        else:
            assert course_of(path) == course, path.name


def test_default_target_picks_most_ancestors_among_accept_edges(tmp_path):
    pipeline = load_pipeline()

    def edge(s, t, decision="ACCEPT"):
        return {"source": s, "target": t, "decision": decision}

    graph = tmp_path / "validated_graph.json"
    graph.write_text(
        json.dumps(
            {
                "edges": [
                    edge("a", "b"),
                    edge("b", "c"),
                    edge("x", "y"),
                    edge("y", "z"),
                    edge("z", "w", "REJECT"),  # would make w deepest, but is not ACCEPT
                    edge("q", "w", "HUMAN_REVIEW"),
                ]
            }
        )
    )

    assert pipeline.default_target(graph) == "c"  # c and z tie on 2 ancestors; c sorts first
