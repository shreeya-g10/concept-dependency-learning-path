"""pipeline.py smoke test for ds101 and ml101, with no LLM.

The four LLM stages (extraction, discovery, validation, quiz generation) are replaced
by fakes that write the shared examples, relabelled with the course_id they received:
extraction and quiz generation from --course-id, later stages from their input file.
learning_path, which makes no LLM call once it is given quiz items, runs for real.
The test checks the step order, the arguments each module gets, and that course_id
is right in every file in the output folder.
"""

import importlib.util
import json
from pathlib import Path

import pytest

from cdlp.shared.io import EXAMPLES

ROOT = Path(__file__).resolve().parents[2]


def load_pipeline():
    spec = importlib.util.spec_from_file_location("pipeline", ROOT / "pipeline.py")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def arg(args, flag):
    return args[args.index(flag) + 1]


def relabel(src: Path, dst: Path, course: str) -> None:
    if src.suffix == ".jsonl":
        rows = [json.loads(line) for line in src.read_text().splitlines() if line.strip()]
        dst.write_text("".join(json.dumps({**r, "course_id": course}) + "\n" for r in rows))
    else:
        dst.write_text(json.dumps({**json.loads(src.read_text()), "course_id": course}))


def course_of(path: Path) -> str:
    return json.loads(Path(path).read_text())["course_id"]


@pytest.mark.parametrize("course", ["ds101", "ml101"])
def test_pipeline_runs_and_keeps_course_id(course, tmp_path, monkeypatch, capsys):
    pipeline = load_pipeline()
    real_run = pipeline.run
    calls = []

    def fake_run(module, *args):
        calls.append((module, args))
        if module == "cdlp.extraction":
            out = Path(arg(args, "--out-dir"))
            cid = arg(args, "--course-id")
            relabel(EXAMPLES / "concepts.json", out / "concepts.json", cid)
            relabel(EXAMPLES / "chunks.jsonl", out / "chunks.jsonl", cid)
        elif module == "cdlp.discovery":
            out = Path(arg(args, "--out-dir"))
            cid = course_of(arg(args, "--concepts"))
            relabel(EXAMPLES / "relationships.json", out / "relationships.json", cid)
        elif module == "cdlp.validation":
            cid = course_of(arg(args, "--relationships"))
            relabel(EXAMPLES / "validated_graph.json", Path(arg(args, "--out")), cid)
        elif module == "cdlp.learning_path.quiz":
            relabel(
                EXAMPLES / "quiz_items.json", Path(arg(args, "--out")), arg(args, "--course-id")
            )
        else:  # learning_path and root_cause make no LLM call: run them for real
            real_run(module, *args)

    monkeypatch.setattr(pipeline, "run", fake_run)
    monkeypatch.setattr("sys.argv", ["pipeline.py", "--course", course, "--out-dir", str(tmp_path)])

    with pytest.raises(SystemExit) as exit_info:
        pipeline.main()

    assert exit_info.value.code == 0, capsys.readouterr().out  # contract check passed
    modules = [m for m, _ in calls]
    assert modules == [
        "cdlp.extraction",
        "cdlp.discovery",
        "cdlp.validation",
        "cdlp.learning_path.quiz",
        "cdlp.learning_path",
    ]

    args = dict(calls)
    assert arg(args["cdlp.extraction"], "--course-id") == course
    assert "--students" not in args["cdlp.learning_path"]  # learning_path builds them
    # quiz items are generated for this course, never the ds101 example
    quiz = arg(args["cdlp.learning_path.quiz"], "--out")
    assert quiz == str(tmp_path / "quiz_items.json")
    assert arg(args["cdlp.learning_path"], "--quiz") == quiz
    assert arg(args["cdlp.learning_path.quiz"], "--course-id") == course
    # questions only for concepts on ACCEPT edges: all 259 ds101 concepts would be ~1,300 calls
    graph = str(tmp_path / "validated_graph.json")
    assert arg(args["cdlp.learning_path.quiz"], "--only-graph") == graph
    # no --target given: the example graph's deepest ACCEPT concept is chosen and printed
    assert arg(args["cdlp.learning_path"], "--target") == "avl_tree"
    assert "target: avl_tree (4 ancestors" in capsys.readouterr().out

    produced = sorted(p.name for p in tmp_path.iterdir())
    assert "sim_students.json" in produced  # generated by learning_path from the graph
    assert "quiz_items.json" in produced
    for path in tmp_path.iterdir():
        if path.suffix == ".jsonl":
            rows = [json.loads(line) for line in path.read_text().splitlines() if line.strip()]
            assert {r["course_id"] for r in rows} == {course}, path.name
        else:
            assert course_of(path) == course, path.name


def test_default_target_picks_most_ancestors_among_accept_edges(tmp_path):
    pipeline = load_pipeline()

    def edge(s, t, decision="ACCEPT"):
        return {"source": s, "target": t, "decision": decision}

    graph = tmp_path / "validated_graph.json"
    graph.write_text(
        json.dumps(
            {
                "edges": [
                    edge("a", "b"),
                    edge("b", "c"),
                    edge("x", "y"),
                    edge("y", "z"),
                    edge("z", "w", "REJECT"),  # would make w deepest, but is not ACCEPT
                    edge("q", "w", "HUMAN_REVIEW"),
                ]
            }
        )
    )

    assert pipeline.default_target(graph) == "c"  # c and z tie on 2 ancestors; c sorts first


@pytest.mark.parametrize("state_written", [True, False])
def test_root_cause_gets_student_state_when_it_exists(state_written, tmp_path, monkeypatch):
    pipeline = load_pipeline()
    calls = {}

    def fake_run(module, *args):
        calls[module] = args
        if module == "cdlp.extraction":
            out = Path(arg(args, "--out-dir"))
            relabel(EXAMPLES / "concepts.json", out / "concepts.json", "ds101")
            relabel(EXAMPLES / "chunks.jsonl", out / "chunks.jsonl", "ds101")
            # answers exist, so the root-cause step runs
            relabel(EXAMPLES / "student_answers.json", out / "student_answers.json", "ds101")
        elif module == "cdlp.discovery":
            relabel(
                EXAMPLES / "relationships.json",
                Path(arg(args, "--out-dir")) / "relationships.json",
                "ds101",
            )
        elif module == "cdlp.validation":
            relabel(EXAMPLES / "validated_graph.json", Path(arg(args, "--out")), "ds101")
        elif module == "cdlp.learning_path" and state_written:
            relabel(
                EXAMPLES / "student_state.json",
                Path(arg(args, "--out-dir")) / "student_state.json",
                "ds101",
            )
        elif module == "cdlp.root_cause":  # faked: its default method calls the LLM
            relabel(EXAMPLES / "root_cause.json", Path(arg(args, "--out")), "ds101")

    monkeypatch.setattr(pipeline, "run", fake_run)
    monkeypatch.setattr(
        "sys.argv", ["pipeline.py", "--course", "ds101", "--out-dir", str(tmp_path)]
    )

    with pytest.raises(SystemExit):
        pipeline.main()

    root_cause = calls["cdlp.root_cause"]
    if state_written:
        assert arg(root_cause, "--state") == str(tmp_path / "student_state.json")
    else:
        assert "--state" not in root_cause


@pytest.mark.parametrize("allow", [True, False])
def test_allow_tfidf_reaches_extraction_only_when_given(allow, tmp_path, monkeypatch):
    pipeline = load_pipeline()
    seen = {}

    class Stop(Exception):
        pass

    def fake_run(module, *args):
        seen[module] = args
        raise Stop  # only the extraction call matters here

    monkeypatch.setattr(pipeline, "run", fake_run)
    argv = ["pipeline.py", "--course", "ds101", "--out-dir", str(tmp_path)]
    monkeypatch.setattr("sys.argv", argv + (["--allow-tfidf"] if allow else []))
    with pytest.raises(Stop):
        pipeline.main()
    assert ("--allow-tfidf" in seen["cdlp.extraction"]) is allow


def test_teacher_decisions_are_reapplied_after_validation(tmp_path, monkeypatch):
    """review_decisions.json in the output folder: apply_review runs (for real) right
    after validation, so a re-run keeps the teacher's decisions."""
    pipeline = load_pipeline()
    real_run = pipeline.run
    calls = []
    relabel(EXAMPLES / "review_decisions.json", tmp_path / "review_decisions.json", "ds101")

    def fake_run(module, *args):
        calls.append(module)
        if module == "cdlp.extraction":
            out = Path(arg(args, "--out-dir"))
            relabel(EXAMPLES / "concepts.json", out / "concepts.json", "ds101")
            relabel(EXAMPLES / "chunks.jsonl", out / "chunks.jsonl", "ds101")
        elif module == "cdlp.discovery":
            out = Path(arg(args, "--out-dir"))
            relabel(EXAMPLES / "relationships.json", out / "relationships.json", "ds101")
        elif module == "cdlp.validation":
            relabel(EXAMPLES / "validated_graph.json", Path(arg(args, "--out")), "ds101")
        elif module == "cdlp.learning_path.quiz":  # LLM stage: faked like the others
            relabel(EXAMPLES / "quiz_items.json", Path(arg(args, "--out")), "ds101")
        else:  # apply_review and learning_path make no LLM call: run them for real
            real_run(module, *args)

    monkeypatch.setattr(pipeline, "run", fake_run)
    monkeypatch.setattr(
        "sys.argv", ["pipeline.py", "--course", "ds101", "--out-dir", str(tmp_path)]
    )
    with pytest.raises(SystemExit) as exit_info:
        pipeline.main()

    assert exit_info.value.code == 0
    assert calls[2:4] == ["cdlp.validation", "cdlp.validation.apply_review"]
    edges = {
        e["id"]: e for e in json.loads((tmp_path / "validated_graph.json").read_text())["edges"]
    }
    assert edges["r5"]["decision"] == "ACCEPT"
    assert edges["r5"]["review"]["decided_by"] == "teacher"


def test_pipeline_passes_quick_build_flags_to_validation(tmp_path, monkeypatch):
    pipeline = load_pipeline()
    seen = {}

    def fake_run(module, *args):
        seen[module] = args
        raise SystemExit(0)  # stop after the first stage that matters

    def stop_after_validation(module, *args):
        if module == "cdlp.validation":
            fake_run(module, *args)
        elif module == "cdlp.extraction":
            out = Path(arg(args, "--out-dir"))
            relabel(EXAMPLES / "concepts.json", out / "concepts.json", "ds101")
            relabel(EXAMPLES / "chunks.jsonl", out / "chunks.jsonl", "ds101")
        elif module == "cdlp.discovery":
            relabel(
                EXAMPLES / "relationships.json",
                Path(arg(args, "--out-dir")) / "relationships.json",
                "ds101",
            )

    monkeypatch.setattr(pipeline, "run", stop_after_validation)
    monkeypatch.setattr(
        "sys.argv",
        [
            "pipeline.py",
            "--course",
            "ds101",
            "--out-dir",
            str(tmp_path),
            "--skip-necessity",
            "--demo-subset",
            "25",
            "--necessity-sample",
            "40",
        ],
    )
    with pytest.raises(SystemExit):
        pipeline.main()

    v = seen["cdlp.validation"]
    assert "--skip-necessity" in v and arg(v, "--demo-subset") == "25"
    assert arg(v, "--necessity-sample") == "40"
